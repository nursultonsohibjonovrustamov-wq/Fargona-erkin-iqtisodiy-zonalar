export function parseLocation(pathname) {
  const parts = pathname.split("/").filter(Boolean);
  const lang = languages.some((l) => l.code === parts[0])
    ? parts.shift()
    : "uz";
  return { lang, route: "/" + parts.join("/") };
}
export function localPath(lang, route = "/") {
  return `/${lang}${route === "/" ? "/" : route}`;
}
export function searchEntries(lang) {
  const t = copy[lang];
  return [
    ...paths.map((route, i) => ({
      route,
      title: t.nav[i],
      description: [
        t.heroText,
        t.regionLead,
        t.zoneIntro,
        t.investorIntro,
        t.resourcesIntro,
        t.contactLead,
      ][i],
    })),
    ...articleSlugs.map((slug, i) => ({
      route: `/resources/${slug}`,
      title: t.articles[i],
      description: t.articleTexts[i],
    })),
  ];
}
