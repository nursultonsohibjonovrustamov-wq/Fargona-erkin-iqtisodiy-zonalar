export function catalogSearchEntries(lang = "uz") {
  return [
    ...catalogZones.map((z) => ({
      route: `/zones/${z.id}`,
      title: z.names[lang] || z.names.uz,
      description: z.names[lang] || z.names.uz,
    })),
    ...catalogProperties.map((p) => ({
      route: `/properties/${p.id}`,
      title: `E-auksion ${p.id}`,
      description: p.full_address,
    })),
  ];
}
export function getCatalogPageTitle(lang, route) {
  const z = catalogZones.find((z) => route === `/zones/${z.id}`);
  return (
    z?.names[lang] ||
    z?.names.uz ||
    (catalogProperties.some((p) => route === `/properties/${p.id}`)
      ? `E-auksion ${route.split("/").pop()}`
      : undefined)
  );
}
